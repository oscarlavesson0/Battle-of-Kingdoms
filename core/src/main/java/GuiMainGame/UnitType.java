package GuiMainGame;

/**
 * Represents the different graphical and animation types of units in the game.
 *
 * <p>This enum is used by {@link CharacterRenderer} to determine which spritesheet
 * and animation set should be loaded for a unit. Each unit type corresponds to a
 * completely different visual style and animation layout.</p>
 */
public enum UnitType {
    KNIGHT, AXEMAN
}
